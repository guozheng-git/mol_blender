"""Refresh the Structure Studio plugin from this checkout and package it for upload.

    python scripts/build_plugin.py            # wheel + preset catalog + dist/*.zip
    python scripts/build_plugin.py --no-zip   # refresh the plugin directory only

The plugin vendors a wheel built from this checkout, so the Claude skill runs the same
renderer as the CLI. Commit the refreshed plugin directory after running this.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "structure-studio"
SKILL = PLUGIN / "skills" / "structure-studio"
DIST = ROOT / "dist"
EXCLUDE = {"__pycache__", ".DS_Store", ".pytest_cache", ".ruff_cache", "studio-output", "studio-work"}


def build_wheel() -> Path:
    target = SKILL / "assets" / "wheels"
    with tempfile.TemporaryDirectory() as temporary:
        build = [sys.executable, "-m", "build", "--wheel", "--outdir", temporary, str(ROOT)]
        if shutil.which("uv"):
            build = ["uv", "build", "--wheel", "--out-dir", temporary, str(ROOT)]
        subprocess.run(build, check=True, capture_output=True)
        wheel = next(Path(temporary).glob("*.whl"))
        for old in target.glob("*.whl"):
            old.unlink()
        target.mkdir(parents=True, exist_ok=True)
        return Path(shutil.copy2(wheel, target / wheel.name))


def preset_catalog() -> list[dict]:
    sys.path.insert(0, str(ROOT))
    from blender_render import presets  # noqa: E402
    gallery = {row["preset"]: row for row in json.loads((ROOT / "examples/presets/gallery.json").read_text())}
    rows = []
    for preset_id, filename, _, description, aliases, family in presets._PRESETS:
        style = json.loads((ROOT / "blender_render" / filename).read_text())
        queries = [s.get("selection", {}).get("query", "") if isinstance(s.get("selection"), dict) else "" for s in style["styles"]]
        chains = sorted({c for q in queries for c in re.findall(r"chain ([A-Za-z0-9,+]+)", q)})
        example = gallery.get(preset_id, {})
        rows.append({"id": preset_id, "aliases": list(aliases), "description": description, "material": family,
                     "representations": sorted({s["style"] for s in style["styles"]}),
                     "width": style["output"]["width"], "height": style["output"]["height"],
                     "samples": style["output"]["samples"], "chain_specific": bool(chains),
                     "chain_selections": chains, "example_structure": example.get("source_id", ""),
                     "default": preset_id == presets.DEFAULT_PRESET})
    return rows


def write_catalog(rows: list[dict]) -> None:
    references = SKILL / "references"
    (references / "presets.json").write_text(json.dumps(rows, indent=2) + "\n")
    lines = ["# Blender presets", "",
             "Generated by `scripts/build_plugin.py` from the renderer's built-in catalog. "
             "Pass the id to `studio.py render --preset ID`.", "",
             "General presets work on any structure. Chain-specific presets select chain IDs from their example "
             "structure; on other structures those selections fall back to the preset's base colors, so check the "
             "result or prefer a general preset.", "",
             "| Preset | Look | Native size | Works on | Example |", "| --- | --- | --- | --- | --- |"]
    for row in rows:
        scope = "any structure" if not row["chain_specific"] else "chains " + ", ".join(row["chain_selections"])
        name = f"`{row['id']}`" + (" (default)" if row["default"] else "")
        lines.append(f"| {name} | {row['description']} | {row['width']}×{row['height']}, {row['samples']} samples "
                     f"| {scope} | {row['example_structure']} |")
    lines += ["", "On CPU-only machines `studio.py render` caps the long edge at 1280 px and samples at 64 unless "
              "`--full-quality` or explicit `--width/--height/--samples` are given.", ""]
    (references / "presets.md").write_text("\n".join(lines))


def files_under(directory: Path):
    for path in sorted(directory.rglob("*")):
        parts = path.relative_to(directory).parts
        hidden = any(part.startswith(".") and part != ".claude-plugin" for part in parts)
        if path.is_file() and not (set(parts) & EXCLUDE) and not hidden and path.suffix != ".pyc":
            yield path


def package() -> list[Path]:
    DIST.mkdir(exist_ok=True)
    plugin_zip, skill_zip = DIST / "structure-studio-plugin.zip", DIST / "structure-studio-skill.zip"
    with zipfile.ZipFile(plugin_zip, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in files_under(PLUGIN):
            archive.write(path, Path("structure-studio") / path.relative_to(PLUGIN))
    with zipfile.ZipFile(skill_zip, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in files_under(SKILL):
            archive.write(path, Path("structure-studio") / path.relative_to(SKILL))
    return [plugin_zip, skill_zip]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-zip", action="store_true")
    args = parser.parse_args(argv)
    wheel = build_wheel()
    rows = preset_catalog()
    write_catalog(rows)
    result = {"wheel": str(wheel.relative_to(ROOT)), "presets": len(rows)}
    if not args.no_zip:
        result["packages"] = [f"{p.relative_to(ROOT)} ({p.stat().st_size / 1e6:.1f} MB)" for p in package()]
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
